// ============================================================
// 生成"身份证号"
// ============================================================
// 每一条数据（动作、组、训练）都需要一个不重复的编号，
// 将来删除某条数据时才不会误伤别的。这个文件只干这一件事。
//
// 【这里埋着一个坑，必须提前防住】
// 浏览器自带一个现成工具叫 crypto.randomUUID()，用它生成编号最省事。
// 但它有个硬性要求：网页必须运行在"安全环境"下 ——
// 要么网址是 https 开头，要么是 localhost。
//
// 而你在手机上测试时，网址是 http://192.168.3.21:5173 ——
// 这是 http 不是 https，浏览器不认它是安全环境，
// 这时 crypto.randomUUID 会变成 undefined，一调用整个页面就崩。
//
// 最要命的是：这个 bug 在电脑上完全正常，只有手机上会炸。
// 所以下面写了两套方案，一套不行就用另一套。
// ============================================================

export function newId(): string {
  // 方案一：官方工具可用时优先用它（电脑上、以及将来部署到 https 之后都走这条）
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID()
  }

  // 方案二：备用方案（手机上用局域网地址访问时走这条）
  // Date.now() 给出"此刻的毫秒数"（一串数字），后面再拼一段随机字符。
  // 两段加起来，重复的概率低到可以忽略。
  // toString(36) 的作用：把数字转成更短的写法（36 进制，用 0-9 和 a-z 表示）
  return Date.now().toString(36) + Math.random().toString(36).slice(2, 10)
}
